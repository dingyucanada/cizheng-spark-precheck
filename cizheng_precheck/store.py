import json
import sqlite3
from datetime import datetime, timezone
from pathlib import Path
from uuid import uuid4


def now():
    return datetime.now(timezone.utc).isoformat()


def uid(prefix):
    return prefix + uuid4().hex[:16]


class Store:
    def __init__(self, root):
        self.root = Path(root)
        self.root.mkdir(parents=True, exist_ok=True)
        with self.connect() as db:
            db.execute("CREATE TABLE IF NOT EXISTS records (id TEXT PRIMARY KEY, kind TEXT NOT NULL, created TEXT NOT NULL, payload TEXT NOT NULL)")

    def connect(self):
        db = sqlite3.connect(self.root / "cases.sqlite3", timeout=20)
        db.execute("PRAGMA journal_mode=WAL")
        return db

    def put(self, kind, record):
        with self.connect() as db:
            db.execute("INSERT INTO records VALUES (?,?,?,?) ON CONFLICT(id) DO UPDATE SET payload=excluded.payload", (record["id"], kind, record.get("created_at", now()), json.dumps(record, ensure_ascii=False)))
        return record

    def get(self, identifier, kind=None):
        with self.connect() as db:
            row = db.execute("SELECT kind,payload FROM records WHERE id=?", (identifier,)).fetchone()
        if not row or kind and row[0] != kind:
            raise KeyError(identifier)
        return json.loads(row[1])

    def listing(self, kind, limit=80):
        with self.connect() as db:
            rows = db.execute("SELECT payload FROM records WHERE kind=? ORDER BY created DESC LIMIT ?", (kind, limit)).fetchall()
        return [json.loads(row[0]) for row in rows]

    def case_dir(self, case_id):
        # Only identifiers generated by this service, never arbitrary path segments.
        import re
        if not re.fullmatch(r"case_[a-f0-9]{16}", case_id):
            raise KeyError(case_id)
        p = self.root / "cases" / case_id
        p.mkdir(parents=True, exist_ok=True)
        return p

    def recover(self):
        for job in self.listing("job", 10000):
            if job["status"] in ("queued", "running"):
                job.update(status="interrupted", stage="任务中断", message="服务重启；原图已保存，可重新生成。", finished_at=now())
                self.put("job", job)
